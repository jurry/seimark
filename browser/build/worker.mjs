import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';

const result = await build({
  entryPoints: ['src/webrtc/worker-entry.ts'],
  bundle: true,
  format: 'esm',
  target: 'es2022',
  write: false,
  logLevel: 'warning',
});

const code = result.outputFiles[0].text;

writeFileSync(
  'src/webrtc/worker-source.ts',
  `// Generated by build/worker.mjs. Do not edit.\nexport const WORKER_SOURCE = ${JSON.stringify(code)};\n`,
);
